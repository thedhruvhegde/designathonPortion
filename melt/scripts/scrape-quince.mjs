/* Build Melt's demo catalog from quince.com category pages.
   - Only fetches /shop/* category pages (allowed by robots.txt); never /p/*, account or checkout paths.
   - 1.5 s between page requests, 300 ms between images. Images downloaded at 600 px.
   - Writes data/quince.json, data/lots.js (stage auction lots) and web/img/quince/*.jpg
   Run:  node scripts/scrape-quince.mjs            (needs network access to www.quince.com + images.quince.com)
   Product names and photos © Quince. Used for a non-commercial designathon prototype, with a link back. */
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SOURCES = [ // [path, melt category, glyph, max products]
  ['home/furniture', 'furniture', 'chair', 14], ['home/rugs', 'decor', 'rug', 8], ['home/all-bath', 'decor', 'bins', 8],
  ['home/travel', 'storage', 'bins', 8], ['women/jackets', 'clothing', 'parka', 8], ['women/sweaters', 'clothing', 'parka', 8],
  ['women/shoes', 'clothing', 'parka', 6], ['men/best-sellers', 'clothing', 'parka', 8], ['women/cashmere', 'clothing', 'parka', 6],
];
const UA = 'MeltDesignathonPrototype/0.1 (student project; polite crawler)';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60);
const KG = { furniture: 14, decor: 3, storage: 4, clothing: 0.8 };
const FT3 = { furniture: 12, decor: 2, storage: 3, clothing: 0.6 };

function products(html) {
  const m = html.match(/<script id="__NEXT_DATA__"[^>]*>([\s\S]*?)<\/script>/); if (!m) return [];
  const out = [], seen = new Set();
  (function walk(o) {
    if (!o || typeof o !== 'object') return;
    if (o.productItem?.title && o.productItem.cardVariants?.length && !seen.has(o.productItem.productId)) { seen.add(o.productItem.productId); out.push(o.productItem); }
    for (const v of Array.isArray(o) ? o : Object.values(o)) walk(v);
  })(JSON.parse(m[1]));
  return out;
}

async function get(url, type = 'text') {
  const r = await fetch(url, { headers: { 'User-Agent': UA, Accept: type === 'text' ? 'text/html' : 'image/*' } });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return type === 'text' ? r.text() : Buffer.from(await r.arrayBuffer());
}

await mkdir(`${ROOT}web/img/quince`, { recursive: true });
const catalog = [];
for (const [path, category, glyph, max] of SOURCES) {
  let list = [];
  try { list = products(await get(`https://www.quince.com/shop/${path}`)); } catch (e) { console.error('skip', path, e.message); }
  console.error(`${path}: ${list.length} products`);
  for (const p of list.slice(0, max)) {
    const v = p.cardVariants[0], retail = v.price?.salePrice ?? v.price?.minPrice ?? 0;
    const imgs = (v.images || []).slice(0, 3), local = [];
    for (const [i, im] of imgs.entries()) {
      const file = `${slugify(p.title)}-${i}.jpg`;
      try { await writeFile(`${ROOT}web/img/quince/${file}`, await get(`${im.url}?w=600&q=72&fm=jpg`, 'bin')); local.push(`./img/quince/${file}`); } catch (e) { console.error('img', e.message); }
      await sleep(300);
    }
    if (!local.length) continue;
    catalog.push({
      name: p.title, category, glyph, brand: 'Quince', color: v.displayConfig?.displayName || '',
      retail, p0: Math.max(5, Math.min(260, Math.round(retail * (category === 'furniture' ? 0.3 : 0.4)))),
      kg: KG[category], ft3: FT3[category], image: local[0], images: local,
      rating: p.reviews?.averageRating ?? p.reviews?.rating ?? null,
      condition: ['Like new', 'Good', 'Good', 'Gently used'][catalog.length % 4],
      blurb: `${v.displayConfig?.displayName ? v.displayConfig.displayName + '. ' : ''}Bought new for $${retail}. Moving out, and it needs a second home.`,
      source: `https://www.quince.com/${v.url || p.slug}`,
    });
  }
  await sleep(1500);
}
// interleave categories so the feed reads like a real mixed marketplace
const byCat = {}; for (const c of catalog) (byCat[c.category] ||= []).push(c);
const mixed = []; for (let i = 0; mixed.length < catalog.length; i++) for (const l of Object.values(byCat)) if (l[i]) mixed.push(l[i]);
await writeFile(`${ROOT}data/quince.json`, JSON.stringify(mixed, null, 1));
// five stage lots for Melt Live: a spread of categories and prices
const pick = (cat, n = 0) => byCat[cat]?.[n];
const lots = [pick('furniture'), pick('clothing'), pick('decor'), pick('storage'), pick('clothing', 3) || pick('furniture', 2)].filter(Boolean)
  .map((c, i) => ({ id: 'L' + (i + 1), name: c.name, glyph: c.glyph, category: c.category, p0: Math.min(150, c.p0), kg: c.kg, image: c.image, story: `List price $${c.retail} new, now melting. Whoever catches it gives it a second life.` }));
await writeFile(`${ROOT}data/lots.js`, `// generated by scripts/scrape-quince.mjs\nexport default ${JSON.stringify(lots, null, 1)};\n`);
console.error(`wrote ${mixed.length} products, ${lots.length} lots`);
